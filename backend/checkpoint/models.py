"""SQLAlchemy models for the local SQLite database.

Conventions
- Primary keys are UUID strings generated by the application (stable across sync).
- All timestamps are UTC. Session-relative offsets are milliseconds from the
  session's `started_at` on one shared timebase (captures, notes, audio, transcript).
- Review state, work status and sharing state are deliberately separate columns.
"""


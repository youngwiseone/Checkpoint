    segment_id: Mapped[Optional[str]] = mapped_column(ForeignKey("transcript_segments.id", ondelete="CASCADE"), nullable=True, index=True)
    note_id: Mapped[Optional[str]] = mapped_column(ForeignKey("notes.id", ondelete="CASCADE"), nullable=True, index=True)
    # direct: explicitly attached (typed note, user) | candidate: time-window association | uncertain: overlaps several
    confidence: Mapped[str] = mapped_column(String(20), default="direct")
    role: Mapped[str] = mapped_column(String(20), default="source")  # source | withdrawal | correction | completion | context
    attached_by: Mapped[str] = mapped_column(String(20), default="system")  # system | ai | user
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utcnow)
    __table_args__ = (
        CheckConstraint("(draft_id IS NOT NULL) OR (work_item_id IS NOT NULL)", name="ck_evidence_owner"),
        CheckConstraint(
            "(capture_id IS NOT NULL) + (segment_id IS NOT NULL) + (note_id IS NOT NULL) = 1",
            name="ck_evidence_single_source",
        ),
    )



class EvidenceLink(Base):
    """Links a card or work item to a capture, transcript segment or note."""

    __tablename__ = "evidence_links"
    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=new_id)
    draft_id: Mapped[Optional[str]] = mapped_column(ForeignKey("draft_items.id", ondelete="CASCADE"), nullable=True, index=True)

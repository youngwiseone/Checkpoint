    # active | paused | ended | interrupted (process died while active; recovered on launch)
    state: Mapped[str] = mapped_column(String(20), default="active", index=True)
    started_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utcnow)
    ended_at: Mapped[Optional[datetime]] = mapped_column(UTCDateTime, nullable=True)
    last_heartbeat_at: Mapped[Optional[datetime]] = mapped_column(UTCDateTime, nullable=True)
    capture_target: Mapped[str] = mapped_column(String(300), default="foreground")
    transcription_mode: Mapped[str] = mapped_column(String(20), default="after")  # live | after | off
    ai_enabled: Mapped[bool] = mapped_column(Boolean, default=False)
    always_ask_context: Mapped[bool] = mapped_column(Boolean, default=False)
    # Organisation (AI) processing summary: none | queued | running | done | failed | cancelled
    processing_state: Mapped[str] = mapped_column(String(20), default="none")
    raw_audio_deleted: Mapped[bool] = mapped_column(Boolean, default=False)
    is_demo: Mapped[bool] = mapped_column(Boolean, default=False)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utcnow)

    project: Mapped[Project] = relationship(back_populates="sessions")
    sources: Mapped[list["AudioSource"]] = relationship(back_populates="session", cascade="all, delete-orphan", passive_deletes=True)


